export function getNoteForStringFret(stringNumber, fret) {
  const info = STRING_INFO.find((s) => s.string === stringNumber);
  if (!info) return { note: 'E4', pitchClass: 'E', midi: 64, freq: 329.63 };
  const midi = info.midi + fret;
  const freq = 440 * Math.pow(2, (midi - 69) / 12);
  const pitchClass = NOTE_NAMES[midi % 12];
  const octave = Math.floor(midi / 12) - 1;
  return {
    note: `${pitchClass}${octave}`,
    pitchClass,
    octave,
    midi,
    freq: Number(freq.toFixed(2)),
  };
}

